export function FeatureGrid({
  title = "Features",
  subtitle,
  features,
  columns = 3,
  background = "gray",
}: FeatureGridProps) {
  const bgClass = {
    white: "bg-white",
    gray: "bg-gray-50",
    navy: "bg-navy",
  }[background];

  const textClass = background === "navy" ? "text-white" : "text-navy";
  const subtitleClass = background === "navy" ? "text-white/70" : "text-gray-600";
  const cardBg = background === "navy" ? "bg-white/10" : "bg-white";
  const iconBg = background === "navy" ? "bg-cs-orange" : "bg-cs-blue/10";
  const iconColor = background === "navy" ? "text-white" : "text-cs-blue";

  const gridCols = {
    2: "md:grid-cols-2",
    3: "md:grid-cols-3",
    4: "md:grid-cols-2 lg:grid-cols-4",
  }[columns];

  return (
    <SectionTracker name="FeatureGrid">
      <section className={`py-16 ${bgClass}`}>
      <div className="mx-auto max-w-7xl px-4 sm:px-6 lg:px-8">
        {/* Header */}
        <div className="text-center mb-12">
          <h2 className={`text-3xl font-semibold ${textClass} mb-4`}>{title}</h2>
          {subtitle && (
            <p className={`${subtitleClass} max-w-2xl mx-auto`}>{subtitle}</p>
          )}
        </div>

        {/* Features Grid */}
        <div className={`grid grid-cols-1 ${gridCols} gap-6`}>
          {features.map((feature, index) => (
            <div
              key={index}
              className={`${cardBg} rounded-xl p-6 text-center`}
            >
              {/* Icon */}
              <div
                className={`w-14 h-14 ${iconBg} rounded-full flex items-center justify-center mx-auto mb-4 ${iconColor}`}
              >
                {iconMap[feature.icon] || (
                  // If icon is a path to an image
                  feature.icon.startsWith("/") ? (
                    <Image
                      src={feature.icon}
                      alt=""
                      width={28}
                      height={28}
                      className="w-7 h-7"
                    />
                  ) : (
                    // Default to showing the icon text
                    <span className="text-lg font-bold">{feature.icon}</span>
                  )
                )}
              </div>

              {/* Content */}
              <h3 className={`text-lg font-semibold ${textClass} mb-2`}>
                {feature.title}
              </h3>
              <p className={`text-sm ${subtitleClass}`}>{feature.description}</p>
            </div>
          ))}
        </div>
      </div>
    </section>
    </SectionTracker>

  );
}
